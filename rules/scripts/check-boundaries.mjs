import { existsSync, readFileSync, readdirSync } from 'node:fs';
const root = new URL('../', import.meta.url);
const repositoryRoot = new URL('../../', import.meta.url);
const enginePrefix = 'link:../../../../rusty-engine/rules/packages/';
const packages = new Map([
  [
    'd20-authoring',
    {
      dependencies: [
        '@rusty-engine/gameplay-rules-authoring',
        '@rusty-engine/gameplay-rules-contracts',
      ],
      devDependencies: ['@types/node'],
    },
  ],
  [
    'starter-ruleset',
    {
      dependencies: ['@rusty-d20/rules-authoring'],
      devDependencies: ['@types/node'],
    },
  ],
]);
const failures = [];

for (const [name, expected] of packages) {
  const manifest = JSON.parse(
    readFileSync(new URL(`packages/${name}/package.json`, root), 'utf8'),
  );
  assertKeys(
    name,
    'dependencies',
    manifest.dependencies,
    expected.dependencies,
  );
  assertKeys(
    name,
    'devDependencies',
    manifest.devDependencies,
    expected.devDependencies,
  );
  if (Object.keys(manifest.exports ?? {}).join(',') !== '.') {
    failures.push(`${name} must expose only its package root`);
  }
}

const authoringManifest = JSON.parse(
  readFileSync(new URL('packages/d20-authoring/package.json', root), 'utf8'),
);
for (const [dependency, path] of [
  ['@rusty-engine/gameplay-rules-authoring', 'gameplay-rules-authoring'],
  ['@rusty-engine/gameplay-rules-contracts', 'gameplay-rules-contracts'],
]) {
  if (authoringManifest.dependencies[dependency] !== `${enginePrefix}${path}`) {
    failures.push(
      `${dependency} does not use the adjacent Engine rules package`,
    );
  }
}

const forbiddenRuntime =
  /\b(?:D20Session|GameRuntime|EntityState|RuntimeBridge|RuleEvaluator|RuleScheduler|ServiceLocator|RuleRegistry|fetch|window|document|localStorage|sessionStorage|indexedDB)\b/g;
for (const name of packages.keys()) {
  walk(new URL(`packages/${name}/src/`, root), (url) => {
    if (!url.pathname.endsWith('.ts')) return;
    const source = readFileSync(url, 'utf8');
    for (const match of source.matchAll(forbiddenRuntime)) {
      failures.push(
        `${relative(url)}:${String(lineAt(source, match.index ?? 0))}: forbidden runtime/browser vocabulary ${match[0]}`,
      );
    }
    for (const match of source.matchAll(
      /@(?:rusty-engine|rusty-d20)\/[^'"]+\/(?:src|dist)\//g,
    )) {
      failures.push(
        `${relative(url)}:${String(lineAt(source, match.index ?? 0))}: deep package import ${match[0]}`,
      );
    }
  });
}

const generated = readFileSync(
  new URL('packages/d20-authoring/src/generated.ts', root),
  'utf8',
);
if (!generated.startsWith('// GENERATED by `cargo run -p rusty-d20')) {
  failures.push('d20 candidate contract lost its Rust ownership marker');
}

const rootWorkspace = new URL('pnpm-workspace.yaml', repositoryRoot);
if (
  existsSync(rootWorkspace) &&
  readFileSync(rootWorkspace, 'utf8').includes('rules/')
) {
  failures.push('authoring rules must stay outside the UI pnpm workspace');
}
const nxIgnore = new URL('.nxignore', repositoryRoot);
if (
  !existsSync(nxIgnore) ||
  !readFileSync(nxIgnore, 'utf8').split(/\r?\n/u).includes('rules/')
) {
  failures.push('authoring rules must stay outside root Nx project discovery');
}
for (const directory of ['apps', 'libs']) {
  walk(new URL(`${directory}/`, repositoryRoot), (url) => {
    if (!url.pathname.endsWith('.ts')) return;
    const source = readFileSync(url, 'utf8');
    if (
      source.includes('@rusty-d20/rules-authoring') ||
      source.includes('@rusty-d20/starter-ruleset')
    ) {
      failures.push(
        `${relative(url)} imports build-time rules into the UI graph`,
      );
    }
  });
}

if (failures.length > 0) {
  throw new Error(
    `Rusty D20 rules boundary violations:\n${failures.join('\n')}`,
  );
}
console.log('Rusty D20 rules package boundaries passed');

function assertKeys(packageName, field, value, expected) {
  const actual = Object.keys(value ?? {}).sort();
  const wanted = [...expected].sort();
  if (JSON.stringify(actual) !== JSON.stringify(wanted)) {
    failures.push(
      `${packageName} ${field} ${JSON.stringify(actual)} do not match ${JSON.stringify(wanted)}`,
    );
  }
}

function walk(url, visit) {
  if (!existsSync(url)) return;
  for (const entry of readdirSync(url, { withFileTypes: true })) {
    const child = new URL(
      `${entry.name}${entry.isDirectory() ? '/' : ''}`,
      url,
    );
    if (entry.isDirectory()) walk(child, visit);
    else visit(child);
  }
}

function lineAt(source, index) {
  return source.slice(0, index).split('\n').length;
}

function relative(url) {
  return url.pathname.slice(repositoryRoot.pathname.length);
}
